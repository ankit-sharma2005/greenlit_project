import { useEffect, useState } from "react";

import { Button } from "./Button";
import { ApiError } from "../lib/api";
import { createDraft, type DatasetDraft, type DraftKind } from "../lib/drafts";
import { fetchPreferences } from "../lib/preferences";
import { listProviders, type Provider } from "../lib/providers";
import "../styles/settings.css";

const KINDS: { value: DraftKind; label: string }[] = [
  { value: "document_fact", label: "Document fact" },
  { value: "unanswerable", label: "Unanswerable" },
  { value: "paraphrase", label: "Paraphrase" },
  { value: "edge_case", label: "Edge case" },
];

interface JudgeChoice {
  provider_id: string;
  model: string;
}

/**
 * Settings → Datasets: ask a model for draft questions.
 *
 * Nothing generated here is usable yet: every item starts pending and must be
 * approved in the review table. When the generator is the same provider and model as
 * the judge, the panel says so and needs an explicit confirmation.
 */
export function DraftGeneratorPanel({
  onCreated,
}: {
  onCreated: (draft: DatasetDraft) => void;
}) {
  const [providers, setProviders] = useState<Provider[]>([]);
  const [judge, setJudge] = useState<JudgeChoice | null>(null);
  const [name, setName] = useState("");
  const [description, setDescription] = useState("");
  const [documents, setDocuments] = useState("");
  const [count, setCount] = useState(10);
  const [kinds, setKinds] = useState<DraftKind[]>(["document_fact"]);
  const [providerId, setProviderId] = useState("");
  const [model, setModel] = useState("");
  const [confirmed, setConfirmed] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    Promise.all([listProviders(), fetchPreferences()])
      .then(([list, preferences]) => {
        if (!active) return;
        setProviders(list.filter((provider) => provider.is_active));
        if (preferences.judge) setJudge(preferences.judge);
        if (preferences.generator) {
          setProviderId(preferences.generator.provider_id);
          setModel(preferences.generator.model);
        }
      })
      .catch(() => {
        /* The form still works; it just starts without saved defaults. */
      });
    return () => {
      active = false;
    };
  }, []);

  function chooseProvider(nextId: string) {
    const provider = providers.find((entry) => entry.id === nextId);
    setProviderId(nextId);
    setModel(provider?.model_name ?? "");
    setConfirmed(false);
  }

  function toggleKind(kind: DraftKind) {
    setKinds((current) =>
      current.includes(kind) ? current.filter((entry) => entry !== kind) : [...current, kind],
    );
  }

  const sameAsJudge =
    judge !== null &&
    providerId !== "" &&
    judge.provider_id === providerId &&
    judge.model.trim().toLowerCase() === model.trim().toLowerCase();

  const complete =
    name.trim() !== "" && description.trim() !== "" && providerId !== "" && model.trim() !== "" &&
    kinds.length > 0;

  async function generate() {
    setBusy(true);
    setError(null);
    setNotice(null);
    try {
      const draft = await createDraft({
        name: name.trim(),
        app_description: description.trim(),
        count,
        kinds,
        documents: documents.trim() ? documents.trim() : undefined,
        provider_id: providerId,
        model: model.trim(),
      });
      onCreated(draft);
      setNotice(
        `Draft with ${draft.items.length} pending item${draft.items.length === 1 ? "" : "s"} ` +
          `generated by ${draft.generated_by_model}. Review each item before publishing.`,
      );
    } catch (caught) {
      setError(
        caught instanceof ApiError
          ? caught.message
          : "Could not generate a draft. Check the provider and try again.",
      );
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="card" aria-labelledby="draft-generator-heading" data-testid="draft-generator">
      <div className="card__header">
        <h2 id="draft-generator-heading">Generate draft questions</h2>
        <p className="card__hint">
          A model writes the questions; you approve each one. Nothing reaches a dataset until it is
          approved and published.
        </p>
      </div>

      <label className="form__label" htmlFor="draft-name">
        Dataset name:
      </label>
      <input
        id="draft-name"
        data-testid="draft-name"
        type="text"
        value={name}
        onChange={(event) => setName(event.target.value)}
        placeholder="Shop assistant questions"
        disabled={busy}
      />

      <label className="form__label" htmlFor="draft-description">
        What does the app do?
      </label>
      <textarea
        id="draft-description"
        data-testid="draft-description"
        rows={3}
        value={description}
        onChange={(event) => setDescription(event.target.value)}
        placeholder="A support assistant for an online shop that answers refund and shipping questions."
        disabled={busy}
      />

      <label className="form__label" htmlFor="draft-documents">
        Optional documents (pasted text):
      </label>
      <textarea
        id="draft-documents"
        data-testid="draft-documents"
        rows={3}
        value={documents}
        onChange={(event) => setDocuments(event.target.value)}
        placeholder="Refund policy, shipping table, FAQ…"
        maxLength={20_000}
        disabled={busy}
      />

      <label className="form__label" htmlFor="draft-count">
        How many questions (1–50)?
      </label>
      <input
        id="draft-count"
        data-testid="draft-count"
        type="number"
        min={1}
        max={50}
        value={count}
        onChange={(event) => setCount(Number(event.target.value))}
        disabled={busy}
      />

      <fieldset className="theme-options" style={{ marginTop: "var(--space-3)" }}>
        <legend className="form__label">Kinds</legend>
        {KINDS.map((kind) => (
          <label key={kind.value}>
            <input
              type="checkbox"
              data-testid={`draft-kind-${kind.value}`}
              checked={kinds.includes(kind.value)}
              onChange={() => toggleKind(kind.value)}
              disabled={busy}
            />{" "}
            {kind.label}
          </label>
        ))}
      </fieldset>

      <label className="form__label" htmlFor="draft-provider">
        Generator provider:
      </label>
      <select
        id="draft-provider"
        data-testid="draft-provider"
        value={providerId}
        onChange={(event) => chooseProvider(event.target.value)}
        disabled={busy}
      >
        <option value="">Pick a provider</option>
        {providers.map((provider) => (
          <option key={provider.id} value={provider.id}>
            {provider.name}
          </option>
        ))}
      </select>

      <label className="form__label" htmlFor="draft-model">
        Generator model:
      </label>
      <input
        id="draft-model"
        data-testid="draft-model"
        type="text"
        value={model}
        onChange={(event) => {
          setModel(event.target.value);
          setConfirmed(false);
        }}
        placeholder="e.g. llama3, gpt-4o-mini"
        disabled={busy}
      />

      {sameAsJudge ? (
        <div className="form-error" role="alert" data-testid="draft-generator-warning">
          <p>
            This is the same provider and model as the judge. The model that writes the questions
            would also grade them.
          </p>
          <label>
            <input
              type="checkbox"
              data-testid="draft-generator-confirm"
              checked={confirmed}
              onChange={(event) => setConfirmed(event.target.checked)}
            />{" "}
            I understand, and want to generate anyway.
          </label>
        </div>
      ) : null}

      {error ? (
        <p className="form-error" role="alert" data-testid="draft-generator-error">
          {error}
        </p>
      ) : null}
      {notice ? (
        <p className="notice" role="status" data-testid="draft-generator-notice">
          {notice}
        </p>
      ) : null}

      <div className="datasets__actions" style={{ marginTop: "var(--space-4)" }}>
        <Button
          type="button"
          variant="primary"
          onClick={() => void generate()}
          loading={busy}
          disabled={!complete || (sameAsJudge && !confirmed)}
          data-testid="draft-generate"
        >
          Generate draft
        </Button>
      </div>
    </section>
  );
}
