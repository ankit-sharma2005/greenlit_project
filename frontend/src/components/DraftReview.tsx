import { useState } from "react";

import { Button } from "./Button";
import { ApiError } from "../lib/api";
import {
  approveAllDraftItems,
  getDraft,
  publishDraft,
  reviewDraftItem,
  type DatasetDraft,
} from "../lib/drafts";
import "../styles/settings.css";

/**
 * The review table for one draft: every item is approved, rejected or edited here, and
 * publishing is refused until at least one item is approved. The publish notice names the
 * model that wrote the items, because a generated dataset that does not say where it came
 * from is worse than one that does.
 */
export function DraftReview({
  draft,
  onChange,
}: {
  draft: DatasetDraft | null;
  onChange: (draft: DatasetDraft) => void;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [editedQuestion, setEditedQuestion] = useState("");
  const [editedAnswer, setEditedAnswer] = useState("");
  const [editedPassage, setEditedPassage] = useState("");

  if (draft === null) {
    return null;
  }
  // A stable binding: the callbacks below are closures over it, and a parameter's
  // narrowing does not survive into a nested function.
  const current = draft;

  const pending = draft.items.filter((item) => item.status === "pending").length;
  const approved = draft.items.filter((item) => item.status === "approved").length;
  const rejected = draft.items.filter((item) => item.status === "rejected").length;
  const published = draft.published_version_id !== null;

  function fail(caught: unknown, fallback: string) {
    setError(caught instanceof ApiError ? caught.message : fallback);
  }

  async function setStatus(itemId: string, status: "approved" | "rejected") {
    setBusy(true);
    setError(null);
    try {
      onChange(await reviewDraftItem(current.id, itemId, { status }));
    } catch (caught) {
      fail(caught, "Could not update that item. Try again.");
    } finally {
      setBusy(false);
    }
  }

  function startEdit(itemId: string, question: string, answer: string, passage: string | null) {
    setEditingId(itemId);
    setEditedQuestion(question);
    setEditedAnswer(answer);
    setEditedPassage(passage ?? "");
  }

  async function saveEdit(itemId: string) {
    setBusy(true);
    setError(null);
    try {
      onChange(
        await reviewDraftItem(current.id, itemId, {
          question: editedQuestion,
          expected_answer: editedAnswer,
          source_passage: editedPassage,
        }),
      );
      setEditingId(null);
    } catch (caught) {
      fail(caught, "Could not save that edit. Try again.");
    } finally {
      setBusy(false);
    }
  }

  async function approveAll() {
    if (!window.confirm(`Approve all ${pending} pending item${pending === 1 ? "" : "s"}?`)) return;
    setBusy(true);
    setError(null);
    try {
      onChange(await approveAllDraftItems(current.id));
    } catch (caught) {
      fail(caught, "Could not approve the pending items. Try again.");
    } finally {
      setBusy(false);
    }
  }

  async function publish() {
    setBusy(true);
    setError(null);
    setNotice(null);
    try {
      const version = await publishDraft(current.id);
      setNotice(
        `Published dataset version ${version.version_no} with ${version.row_count} item${
          version.row_count === 1 ? "" : "s"
        }. Generated by ${current.generated_by_model}; only approved items are included.`,
      );
      onChange(await getDraft(current.id));
    } catch (caught) {
      fail(caught, "Could not publish this draft. Try again.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="card" aria-labelledby="draft-review-heading" data-testid="draft-review">
      <div className="card__header">
        <h2 id="draft-review-heading">Review “{draft.name}”</h2>
        <span className="badge" data-testid="draft-review-status">
          {draft.status}
        </span>
      </div>
      <p className="card__hint" data-testid="draft-review-provenance">
        Generated by {draft.generated_by_model} on {draft.generator_provider_name}, prompt{" "}
        {draft.prompt_version}. Only approved items are published.
        {draft.same_as_judge
          ? " The generator is also the judge, so this dataset was flagged when it was created."
          : ""}
      </p>

      <div className="datasets__actions" style={{ marginBottom: "var(--space-3)" }}>
        <span className="badge" data-testid="draft-count-pending">
          {pending} pending
        </span>
        <span className="badge" data-testid="draft-count-approved">
          {approved} approved
        </span>
        <span className="badge" data-testid="draft-count-rejected">
          {rejected} rejected
        </span>
      </div>

      {error ? (
        <p className="form-error" role="alert" data-testid="draft-review-error">
          {error}
        </p>
      ) : null}
      {notice ? (
        <p className="notice" role="status" data-testid="draft-review-notice">
          {notice}
        </p>
      ) : null}

      <table className="results__table" data-testid="draft-items">
        <thead>
          <tr>
            <th scope="col">Question</th>
            <th scope="col">Expected answer</th>
            <th scope="col">Kind</th>
            <th scope="col">State</th>
            <th scope="col">Review</th>
          </tr>
        </thead>
        <tbody>
          {draft.items.map((item) => (
            <tr key={item.id} data-testid={`draft-item-${item.id}`}>
              <td>
                {editingId === item.id ? (
                  <textarea
                    aria-label="Question"
                    data-testid={`draft-item-question-${item.id}`}
                    value={editedQuestion}
                    onChange={(event) => setEditedQuestion(event.target.value)}
                    rows={3}
                  />
                ) : (
                  item.question
                )}
              </td>
              <td>
                {editingId === item.id ? (
                  <textarea
                    aria-label="Expected answer"
                    data-testid={`draft-item-answer-${item.id}`}
                    value={editedAnswer}
                    onChange={(event) => setEditedAnswer(event.target.value)}
                    rows={3}
                  />
                ) : (
                  item.expected_answer
                )}
              </td>
              <td>{item.kind.replaceAll("_", " ")}</td>
              <td data-testid={`draft-item-status-${item.id}`}>
                {item.status}
                {item.edited ? " · edited" : ""}
              </td>
              <td>
                {editingId === item.id ? (
                  <>
                    <Button
                      variant="primary"
                      onClick={() => void saveEdit(item.id)}
                      disabled={busy}
                      data-testid={`draft-item-save-${item.id}`}
                    >
                      Save
                    </Button>{" "}
                    <Button
                      variant="ghost"
                      onClick={() => setEditingId(null)}
                      disabled={busy}
                      data-testid={`draft-item-cancel-${item.id}`}
                    >
                      Cancel
                    </Button>
                  </>
                ) : (
                  <>
                    <Button
                      variant="secondary"
                      onClick={() => void setStatus(item.id, "approved")}
                      disabled={busy || item.status === "approved"}
                      data-testid={`draft-item-approve-${item.id}`}
                    >
                      Approve
                    </Button>{" "}
                    <Button
                      variant="secondary"
                      onClick={() => void setStatus(item.id, "rejected")}
                      disabled={busy || item.status === "rejected"}
                      data-testid={`draft-item-reject-${item.id}`}
                    >
                      Reject
                    </Button>{" "}
                    <Button
                      variant="ghost"
                      onClick={() =>
                        startEdit(item.id, item.question, item.expected_answer, item.source_passage)
                      }
                      disabled={busy}
                      data-testid={`draft-item-edit-${item.id}`}
                    >
                      Edit
                    </Button>
                  </>
                )}
              </td>
            </tr>
          ))}
        </tbody>
      </table>

      <div className="datasets__actions" style={{ marginTop: "var(--space-3)" }}>
        <Button
          variant="secondary"
          onClick={() => void approveAll()}
          disabled={busy || pending === 0}
          data-testid="draft-approve-all"
        >
          Approve all pending
        </Button>
        <Button
          variant="primary"
          onClick={() => void publish()}
          disabled={busy || approved === 0 || published}
          data-testid="draft-publish"
        >
          Publish dataset
        </Button>
      </div>
    </section>
  );
}
